// Создано: 2026-09-14 — R17 «Полнота сейва» (аудит-0911 E-1):
// масштабируемый контракт сброса world-scoped доменов.
//
// ДО R17 сброс был размазан и асимметричен режимам:
//   • NewGame  — NpcDomainResetPhase (фаза 0) чистила ТОЛЬКО NPC-домен;
//   • LoadGame — GameSession жёстко звал _npcModule.ResetWorld();
//   • звери/формации/игрок/инвентарь/кукла/пояс/время/квесты/валюта —
//     переживали пересборку (ghost-animals, дюп экипировки, «призраки»
//     прошлого мира, E-1/E-3 аудита).
//
// Контракт: реализует ЛЮБОЙ доменный сервис, чьё состояние привязано к
// конкретному миру (а не к процессу). WorldDomainResetPhase (фаза 0,
// NewGame) и GameSession.LoadGame резолвят ResolveAll<IWorldResettable>()
// и сбрасывают ВСЁ — новые модули подключаются декларативно, без правок
// фазы/сессии.
//
// СЕМАНТИКА ResetWorld(): вернуть сервис в состояние «свежего процесса»
// (как будто мир ещё не создавался). Идемпотентен. НЕ трогает
// процесс-scoped контент (каталоги предметов/локаций — они регистрируются
// на старте процесса и не являются состоянием мира).
namespace CultivationGame.Core.Interfaces;

/// <summary>
/// World-scoped домен, переживаемый пересборку мира. Реализаторы обязаны
/// сбрасывать своё состояние до «свежего процесса» (идемпотентно).
/// Вызывается WorldDomainResetPhase (NewGame) и GameSession.LoadGame
/// (до RestoreState — сейв наполнит домен заново).
/// </summary>
public interface IWorldResettable
{
    void ResetWorld();
}
