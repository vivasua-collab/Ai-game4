namespace CultivationGame.Core.Data
{
    /// <summary>
    /// Канонические константы экономики (СТАБ, R22-1).
    /// Спецификация: docs/docs_v2/06_player/ECONOMY_SYSTEM.md.
    /// Использование: CurrencyExchangeService (Modules/Trade) и будущая
    /// проводка торговли. Числа менять ТОЛЬКО по указанию пользователя.
    /// </summary>
    public static class EconomyConstants
    {
        // === Курс (канон, 2026-09-20) ===

        /// <summary>
        /// Курс обмена: 1 духовный камень = 100 золота.
        /// Основа всех котировок (спред применяется поверх).
        /// </summary>
        public const int GoldPerSpiritStone = 100;

        // === Спред обмена камней (зеркалит товарный TradeConfig) ===

        /// <summary>
        /// Покупка камня у торговца: 1200‰ = ×1.2 от курса.
        /// Игрок платит GoldPerSpiritStone × 1.2 золота за камень.
        /// </summary>
        public const int StoneBuyMarkupPermil = 1200;

        /// <summary>
        /// Продажа камня торговцу: 500‰ = ×0.5 от курса.
        /// Игрок получает GoldPerSpiritStone × 0.5 золота за камень.
        /// </summary>
        public const int StoneSellPermil = 500;

        // === Правила владения ===

        /// <summary>
        /// Смертным НЕ владеть камнями: камни Ци — валюта культиваторов.
        /// NPC-смертный (CultivationLevel.None) оперирует ТОЛЬКО золотом:
        /// не принимает/не предлагает камни, не имеет их в лавке.
        /// Игрок стартует смертным, но практикует — исключение из правила
        /// (см. ECONOMY_SYSTEM §3).
        /// </summary>
        public static bool CanHoldSpiritStones(CultivationLevel level)
        {
            return level != CultivationLevel.None;
        }
    }
}
