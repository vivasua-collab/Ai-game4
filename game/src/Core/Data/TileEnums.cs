using System;

namespace CultivationGame.Core.Data
{
    /// <summary>
    /// Тип поверхности тайла.
    /// Влияет на проходимость и стоимость движения.
    /// Источник: TILE_SYSTEM.md §2
    /// </summary>
    public enum TerrainType
    {
        None = 0,           // Пустота (нет тайла)
        Grass = 1,          // Трава (базовая проходимость, moveCost = 1.0)
        Dirt = 2,           // Земля (базовая проходимость, moveCost = 1.0)
        Stone = 3,          // Камень (базовая проходимость, moveCost = 1.0)
        Water_Shallow = 4,  // Мелкая вода (замедление ×2.0, проходимо)
        Water_Deep = 5,     // Глубокая вода (непроходимо без навыка)
        Sand = 6,           // Песок (небольшое замедление ×1.2)
        Snow = 7,           // Снег (замедление ×1.5)
        Ice = 8,            // Лёд (скольжение, особая механика)
        Lava = 9,           // Лава (урон, непроходимо без защиты)
        Void = 10,          // Пустота (непроходимо)
        Road = 11           // Дорога (бонус скорости ×0.7, проходимо)
    }

    /// <summary>
    /// Категория объекта на тайле.
    /// </summary>
    public enum ObjectCategory
    {
        None = 0,           // Нет объекта
        Vegetation = 1,     // Растительность (деревья, кусты)
        Rock = 2,           // Камни
        Interactive = 3,    // Интерактивные (сундуки, руда, травы)
        Building = 4,       // Здания и сооружения
        Decoration = 5      // Декорации
    }

    /// <summary>
    /// Тип объекта на тайле.
    /// Группировка: 100-199 = Vegetation, 200-299 = Rock, 500-599 = Interactive.
    /// Источник: Legacy TileEnums.cs
    /// </summary>
    public enum ObjectType
    {
        None = 0,

        // === Растительность (100-199) ===
        Tree_Oak = 100,     // Дуб (непроходимо, рубится, дрова)
        Tree_Pine = 101,    // Сосна (непроходимо, рубится, дрова)
        Tree_Birch = 102,   // Берёза (непроходимо, рубится, дрова)
        Bush = 110,         // Куст (замедление, скрытность)
        Bush_Berry = 111,   // Ягодный куст (собираемый, ягоды)

        // === Камни (200-299) ===
        Rock_Small = 200,   // Малый камень (непроходимо, ломается)
        Rock_Medium = 201,  // Средний камень (непроходимо, ломается)
        Rock_Large = 202,   // Большой камень (непроходимо, ломается)

        // === Интерактивные (500-599) ===
        Chest = 500,        // Сундук (открыть/взломать)
        OreVein = 520,      // Рудная жила (добывать, iron_ore)
        Herb = 530          // Трава (собирать, medicinal_herb)
    }

    /// <summary>
    /// Тир прочности объекта.
    /// Определяет минимальный тир инструмента для разрушения/добычи.
    /// Источник: LOCATION_MAP_SYSTEM.md §3 — кирка L1+ для T1, L3+ для T3
    ///           EQUIPMENT_SYSTEM.md §3 — 5 тиров материалов
    /// </summary>
    public enum HardnessTier
    {
        None = 0,       // Нет прочности (не разрушаемо или не имеет тира)
        Organic = 1,    // Органика: дерево, кусты — ломается голыми руками/камнем
        Stone = 2,      // Камень: нужен инструмент T1+ (каменный/железный)
        Metal = 3,      // Металл/руда: нужен инструмент T2+ (стальной)
        Spiritual = 4,  // Духовный: нужен инструмент T3+ (духовная сталь)
        Void = 5        // Неразрушимо: нужен инструмент T5+ (первозданная материя)
    }

    /// <summary>
    /// Флаги свойств тайла.
    /// Источник: Legacy TileEnums.cs GameTileFlags
    /// </summary>
    [Flags]
    public enum TileFlags
    {
        None = 0,
        Passable = 1 << 0,          // Можно пройти
        Swimable = 1 << 1,          // Можно плыть
        Flyable = 1 << 2,           // Можно летать над
        BlocksVision = 1 << 3,      // Блокирует видимость
        ProvidesCover = 1 << 4,     // Даёт укрытие
        Interactable = 1 << 5,      // Можно взаимодействовать
        Harvestable = 1 << 6,       // Можно собирать ресурсы
        Dangerous = 1 << 7          // Опасно (урон)
    }
}
